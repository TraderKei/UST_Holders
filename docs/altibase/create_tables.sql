-- UST Holders v2 Altibase relational schema design draft 2026-10-28
-- Not tested on the company Altibase instance. DBA review is required.
-- All VARCHAR sizes are bytes and at most 2000; no JSON/CLOB/BOOLEAN/UUID type.
-- UUID values and UTC DATE values are bound by the application.
-- DBA must choose tablespaces, grants, driver and version-specific options.
-- Run on a NEW schema only. This script contains no DROP/ALTER/DELETE.
-- Enumerations, month validity and cross-dataset consistency: see design HTML.

-- UST_LOAD_RUN 수집 실행 이력
CREATE TABLE UST_LOAD_RUN (
    RUN_ID VARCHAR(36) NOT NULL,
    STARTED_AT DATE NOT NULL,
    FINISHED_AT DATE,
    RUN_STATUS VARCHAR(16) NOT NULL,
    TRIGGER_TYPE VARCHAR(16) NOT NULL,
    INPUT_DIGEST CHAR(64),
    RESULT_DATASET_ID VARCHAR(36),
    ERROR_CODE VARCHAR(40),
    ERROR_MESSAGE VARCHAR(2000),
    CONSTRAINT PK_UST_RUN PRIMARY KEY (RUN_ID)
);
CREATE INDEX IX_UST_RUN_TIME ON UST_LOAD_RUN (STARTED_AT);

-- UST_DATASET 자료 버전
CREATE TABLE UST_DATASET (
    DATASET_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    INPUT_DIGEST CHAR(64) NOT NULL,
    RULE_VERSION VARCHAR(40) NOT NULL,
    SCHEMA_VERSION INTEGER NOT NULL,
    FIRST_MONTH CHAR(7) NOT NULL,
    LATEST_MONTH CHAR(7) NOT NULL,
    DATA_STATUS VARCHAR(16) NOT NULL,
    CREATED_AT DATE NOT NULL,
    VALIDATED_AT DATE,
    PUBLISHED_AT DATE,
    IS_PRELIMINARY CHAR(1),
    HISTORY_JOIN CHAR(7) NOT NULL,
    TRANSACTION_START CHAR(7) NOT NULL,
    OVERLAP_ROWS INTEGER NOT NULL,
    OVERLAP_DIFFS INTEGER NOT NULL,
    CROSS_CHECKS INTEGER NOT NULL,
    HIST_ONLY_ENTITIES INTEGER NOT NULL,
    ENTITY_COUNT INTEGER NOT NULL,
    MONTH_COUNT INTEGER NOT NULL,
    RECORD_COUNT INTEGER NOT NULL,
    CONSTRAINT PK_UST_DATA PRIMARY KEY (DATASET_ID),
    CONSTRAINT FK_UST_DATA_RUN FOREIGN KEY (RUN_ID) REFERENCES UST_LOAD_RUN (RUN_ID)
);
CREATE INDEX IX_UST_DATA_INPUT ON UST_DATASET (INPUT_DIGEST);

-- UST_SOURCE_FILE 원본 파일 이력
CREATE TABLE UST_SOURCE_FILE (
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    DATASET_ID VARCHAR(36),
    SOURCE_CODE VARCHAR(8) NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    OFFICIAL_URL VARCHAR(1000) NOT NULL,
    STORAGE_URI VARCHAR(1000) NOT NULL,
    DOWNLOADED_AT DATE NOT NULL,
    PUBLISHED_AT DATE,
    SHA256_HEX CHAR(64) NOT NULL,
    BYTE_SIZE BIGINT NOT NULL,
    NATIVE_UNIT VARCHAR(24) NOT NULL,
    SOURCE_LATEST_MONTH CHAR(7),
    CONSTRAINT PK_UST_SOURCE PRIMARY KEY (SOURCE_FILE_ID),
    CONSTRAINT FK_UST_SOURCE_RUN FOREIGN KEY (RUN_ID) REFERENCES UST_LOAD_RUN (RUN_ID),
    CONSTRAINT FK_UST_SOURCE_DATA FOREIGN KEY (DATASET_ID) REFERENCES UST_DATASET (DATASET_ID),
    CONSTRAINT UQ_UST_SOURCE_RUN UNIQUE (RUN_ID, SOURCE_CODE)
);
CREATE INDEX IX_UST_SOURCE_DATA ON UST_SOURCE_FILE (DATASET_ID, SOURCE_CODE);

-- UST_ENTITY 버전별 국가와 구분
CREATE TABLE UST_ENTITY (
    DATASET_ID VARCHAR(36) NOT NULL,
    COUNTRY_CODE VARCHAR(10) NOT NULL,
    COUNTRY_NAME VARCHAR(600) NOT NULL,
    REGION_NAME VARCHAR(120),
    RECORD_TYPE VARCHAR(16) NOT NULL,
    RANK_ELIGIBLE CHAR(1) NOT NULL,
    DISPLAY_ORDER INTEGER NOT NULL,
    CONSTRAINT PK_UST_ENTITY PRIMARY KEY (DATASET_ID, COUNTRY_CODE),
    CONSTRAINT FK_UST_ENTITY_DATA FOREIGN KEY (DATASET_ID) REFERENCES UST_DATASET (DATASET_ID),
    CONSTRAINT UQ_UST_ENTITY_ORD UNIQUE (DATASET_ID, DISPLAY_ORDER)
);

-- UST_HOLDING 월별 보유액과 거래
CREATE TABLE UST_HOLDING (
    DATASET_ID VARCHAR(36) NOT NULL,
    COUNTRY_CODE VARCHAR(10) NOT NULL,
    REFERENCE_MONTH CHAR(7) NOT NULL,
    TOTAL_USD_MN NUMERIC(20,3),
    LT_USD_MN NUMERIC(20,3),
    ST_USD_MN NUMERIC(20,3),
    NET_USD_MN NUMERIC(20,3),
    LT_NET_USD_MN NUMERIC(20,3),
    ST_NET_USD_MN NUMERIC(20,3),
    LT_VAL_USD_MN NUMERIC(20,3),
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    SOURCE_ROW_NO INTEGER NOT NULL,
    CONSTRAINT PK_UST_HOLD PRIMARY KEY (DATASET_ID, COUNTRY_CODE, REFERENCE_MONTH),
    CONSTRAINT FK_UST_HOLD_ENTITY FOREIGN KEY (DATASET_ID, COUNTRY_CODE) REFERENCES UST_ENTITY (DATASET_ID, COUNTRY_CODE),
    CONSTRAINT FK_UST_HOLD_SOURCE FOREIGN KEY (SOURCE_FILE_ID) REFERENCES UST_SOURCE_FILE (SOURCE_FILE_ID)
);
CREATE INDEX IX_UST_HOLD_MONTH ON UST_HOLDING (DATASET_ID, REFERENCE_MONTH);

-- UST_TABLE5 Table 5 대조 값
CREATE TABLE UST_TABLE5 (
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    SOURCE_ROW_NO INTEGER NOT NULL,
    REFERENCE_MONTH CHAR(7) NOT NULL,
    SOURCE_NAME VARCHAR(600) NOT NULL,
    COUNTRY_CODE VARCHAR(10),
    VALUE_USD_BN NUMERIC(20,3),
    MAP_STATUS VARCHAR(16) NOT NULL,
    CONSTRAINT PK_UST_T5 PRIMARY KEY (SOURCE_FILE_ID, SOURCE_ROW_NO, REFERENCE_MONTH),
    CONSTRAINT FK_UST_T5_SOURCE FOREIGN KEY (SOURCE_FILE_ID) REFERENCES UST_SOURCE_FILE (SOURCE_FILE_ID)
);

-- UST_VALID_RESULT 검증 결과
CREATE TABLE UST_VALID_RESULT (
    VALID_RESULT_ID VARCHAR(36) NOT NULL,
    DATASET_ID VARCHAR(36) NOT NULL,
    RULE_CODE VARCHAR(40) NOT NULL,
    SEVERITY VARCHAR(8) NOT NULL,
    RESULT_STATUS VARCHAR(8) NOT NULL,
    CHECKED_COUNT INTEGER NOT NULL,
    FAILED_COUNT INTEGER NOT NULL,
    COUNTRY_CODE VARCHAR(10),
    REFERENCE_MONTH CHAR(7),
    EXPECTED_VALUE NUMERIC(20,6),
    ACTUAL_VALUE NUMERIC(20,6),
    MESSAGE VARCHAR(2000),
    CHECKED_AT DATE NOT NULL,
    CONSTRAINT PK_UST_VALID PRIMARY KEY (VALID_RESULT_ID),
    CONSTRAINT FK_UST_VALID_DATA FOREIGN KEY (DATASET_ID) REFERENCES UST_DATASET (DATASET_ID)
);
CREATE INDEX IX_UST_VALID_DATA ON UST_VALID_RESULT (DATASET_ID, RULE_CODE);

-- UST_SERVICE_STATE 현재 서비스 지정
CREATE TABLE UST_SERVICE_STATE (
    SERVICE_KEY VARCHAR(30) NOT NULL,
    CURRENT_DATASET_ID VARCHAR(36),
    UPDATED_AT DATE NOT NULL,
    UPDATED_BY VARCHAR(80) NOT NULL,
    CONSTRAINT PK_UST_SERVICE PRIMARY KEY (SERVICE_KEY),
    CONSTRAINT FK_UST_SERVICE_DATA FOREIGN KEY (CURRENT_DATASET_ID) REFERENCES UST_DATASET (DATASET_ID)
);

